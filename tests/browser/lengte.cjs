const { chromium, BASE, wait, phone, ok, failures } = require('./lib.cjs')
const { SHOTS: out } = require('./lib.cjs')
;(async () => {
  const b = await chromium.launch()
  const { page: p, errors, swipe, swipeTo, pos, state } = await phone(b)
  const base = Date.now()
  const open = async (offset) => { await p.clock.setFixedTime(new Date(base + offset * 86400000)); await p.goto(BASE); await p.waitForSelector('.card, .done') }
  const setLength = async (name) => { await p.locator('#toggle-topics').tap(); await p.waitForSelector('.topics'); await p.locator('.topic', { hasText: name }).locator('input').check(); const note = await p.innerText('.topics [role=status]'); await p.locator('text=Terug naar de editie').tap(); await p.waitForSelector('.card, .done'); return note }
  await open(0)
  ok('standaard uitgebreid: 17 kaarten', await p.locator('.steps li').count() === 17)
  await p.locator('#toggle-topics').tap(); await p.waitForSelector('.topics')
  ok('scherm heet Instellingen, met lengte en onderwerpen', await p.innerText('.topics h2') === 'Instellingen' && await p.locator('.topic input[type=radio]').count() === 2 && await p.locator('.topic input[type=radio]:checked').getAttribute('value') === 'long' && await p.locator('.topic input[type=checkbox]').count() === 5)
  await p.screenshot({ path: out + '/100-instellingen.png', fullPage: true })
  await p.locator('text=Terug naar de editie').tap()
  await setLength('Kort')
  ok('kort: 15 kaarten', await p.locator('.steps li').count() === 15 && await pos() === '1 / 15')
  const sources = []
  for (let i = 0; i < 4; i++) { sources.push((await p.innerText('.card__foot')).split('\n')[0].replace('Bron: ', '').replace(' ↗', '')); await swipe() }
  ok('vier nieuwskaarten, één per bron', JSON.stringify(sources) === JSON.stringify(['NOS', 'RTV Drenthe', 'BBC News', 'The Guardian']), sources.join(', '))
  const topicKickers = []
  for (let i = 0; i < 2; i++) { topicKickers.push((await p.innerText('.card__kicker')).toUpperCase()); await swipe() }
  ok('ook in de korte editie: Tech en AI, daarna Kort nieuws', JSON.stringify(topicKickers) === '["TECH","AI"]' && await p.locator('.card--brief').count() === 1, topicKickers.join(', '))
  await setLength('Uitgebreid')
  ok('terug naar uitgebreid: zelfde kaart, andere positie', await p.locator('.card--brief').count() === 1 && await pos() === '9 / 17')
  for (let i = 0; i < 3; i++) await swipe('right')
  ok('op de zesde nieuwskaart', await pos() === '6 / 17')
  await setLength('Kort')
  ok('kaart valt weg: verder bij de eerste kaart na het gewone nieuws (Tech)', (await p.innerText('.card__kicker')).toUpperCase() === 'TECH' && await pos() === '5 / 15')
  await swipeTo('.card--history'); await p.locator('.option', { hasText: '1760' }).tap(); await wait(450)
  await setLength('Uitgebreid')
  ok('geraden kaart blijft omgedraaid op de juiste plek', await pos() === '10 / 17' && await p.locator('.card--history .result').count() === 1)
  await swipe(); await p.locator('.skip').tap(); await wait(450); await swipe(); await p.locator('.skip').tap(); await wait(450); await swipeTo('.card--quiz')
  for (const q of await p.locator('.question').all()) await q.locator('.option').first().tap()
  await swipe(); await p.waitForSelector('.done')
  const note = await setLength('Kort')
  ok('na afronden: melding vanaf morgen, vandaag ongewijzigd', note.includes('vanaf morgen') && (await state()).length === 'short' && Object.values((await state()).progress)[0].short === false)
  await p.locator('text=Editie teruglezen').tap(); await p.waitForSelector('.card')
  ok('teruglezen van vandaag blijft 17 kaarten', await p.locator('.steps li').count() === 17)
  await open(1)
  ok('morgen: korte editie', await p.locator('.steps li').count() === 15)
  await p.reload(); await p.waitForSelector('.card')
  ok('keuze blijft na herladen', await p.locator('.steps li').count() === 15 && (await state()).length === 'short')
  console.log('console errors:', errors, '| mislukt:', failures()); await b.close(); process.exit(failures() || errors.length ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
