const { chromium, BASE, wait, phone, ok, failures } = require('./lib.cjs')
;(async () => {
  const b = await chromium.launch()
  const { page: p, errors, swipe, pos } = await phone(b)
  await p.goto(BASE); await p.waitForSelector('.card')
  const card = await p.locator('.card').boundingBox()
  const below = Math.min(card.y + card.height + 80, 740)
  ok('er is lege ruimte onder de kaart', below > card.y + card.height + 20, `kaart tot ${Math.round(card.y + card.height)}, veeg op ${Math.round(below)}`)
  await swipe('left', below); ok('veeg in de lege ruimte onder de kaart: volgende', await pos() === '2 / 12')
  await swipe('right', below); ok('veeg naar rechts in de lege ruimte: vorige', await pos() === '1 / 12')
  await swipe('right', below); ok('eerste kaart: veert terug', await pos() === '1 / 12')
  await swipe('left'); ok('veeg op de kaart werkt nog', await pos() === '2 / 12')
  // verticaal scrollen in het vlak blijft werken (geen navigatie)
  const cdp = await p.context().newCDPSession(p)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 200, y: 600 }] })
  for (let i = 1; i <= 6; i++) { await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 200, y: 600 - i * 40 }] }); await wait(12) }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await wait(300)
  ok('verticale veeg bladert niet', await pos() === '2 / 12')
  await p.locator('.save').tap(); ok('tikken op een knop werkt', (await p.innerText('#toggle-saved')).includes('(1)'))
  console.log('console errors:', errors, '| mislukt:', failures()); await b.close(); process.exit(failures() || errors.length ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
