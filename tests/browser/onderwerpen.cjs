const { chromium, devices, BASE, wait, phone, mockWiki, mockTranslate, ok, failures } = require('./lib.cjs')
const { SHOTS: out } = require('./lib.cjs')
;(async () => {
  const { facts } = await import(require('url').pathToFileURL(require('path').join(__dirname, '../../content/facts.js')).href)
  const { deepdives } = await import(require('url').pathToFileURL(require('path').join(__dirname, '../../content/deepdives.js')).href)
  const topicOf = (id, list) => list.find((i) => i.id === id)?.topic
  const b = await chromium.launch()
  const { page: p, errors, swipe, swipeTo, pos, state } = await phone(b)
  const base = Date.now()
  const open = async (offset) => { await p.clock.setFixedTime(new Date(base + offset * 86400000)); await p.goto(BASE); await p.waitForSelector('.card, .done') }
  const picks = async () => Object.values((await state()).progress)[0].picks
  const finishDay = async () => {
    await swipeTo('.card--history')
    await p.locator('.option', { hasText: '1760' }).tap(); await wait(450); await swipe()
    await p.locator('.skip').tap(); await wait(450); await swipe()
    await p.locator('.skip').tap(); await wait(450); await swipeTo('.card--quiz')
    for (const q of await p.locator('.question').all()) await q.locator('.option').first().tap()
    await swipe()
  }

  console.log('== Onderwerpen kiezen')
  await open(0)
  const before = await picks()
  console.log('   standaard vandaag:', before.fact, `(${topicOf(before.fact, facts)})`, '|', before.deepdive, `(${topicOf(before.deepdive, deepdives)})`)
  await p.locator('#toggle-topics').tap(); await p.waitForSelector('.topics')
  ok('5 thema\'s, allemaal aan, met aantallen', await p.locator('.topic input[type=checkbox]:checked').count() === 5 && (await p.locator('.topic:has(input[type=checkbox]) .topic__count').first().innerText()).includes('19 weetjes'), (await p.locator('.topic').allInnerTexts()).map((t) => t.replace(/\n+/g, ' — ')).join(' | '))
  await p.screenshot({ path: out + '/70-onderwerpen.png' })
  for (const name of ['Nederland', 'Wereldgeschiedenis', 'Wetenschap & techniek', 'Taal & cultuur']) await p.locator('.topic', { hasText: name }).locator('input').uncheck()
  ok('laatste thema kan niet uit', await p.locator('.topic input[type=checkbox]:checked').count() === 1 && await p.locator('.topic input[type=checkbox]:checked').isDisabled(), await p.innerText('.topics [role=status]'))
  await p.screenshot({ path: out + '/71-onderwerpen-een.png' })
  let now = await picks()
  ok('weetje en verdieping van vandaag meteen uit Natuur & aarde', topicOf(now.fact, facts) === 'natuur' && topicOf(now.deepdive, deepdives) === 'natuur', `${now.fact} | ${now.deepdive}`)
  ok('keuze opgeslagen', JSON.stringify((await state()).topics) === '["natuur"]')
  await p.locator('text=Terug naar de editie').tap(); await p.waitForSelector('.card')
  await swipeTo('.card--history')
  await p.locator('.option', { hasText: '1760' }).tap(); await wait(450); await swipe()
  await p.locator('.skip').tap(); await wait(450); await swipe()
  await p.locator('.skip').tap(); await wait(450)
  const shownFact = await p.innerText('.card__title')
  ok('kaart 10 toont het gekozen weetje', shownFact === facts.find((f) => f.id === now.fact).title, shownFact)
  ok('weetje heeft nu een bronlink', (await p.getAttribute('.card__foot a', 'href')).startsWith('https://nl.wikipedia.org/wiki/'))
  await swipe()
  const chosen = deepdives.find((d) => d.id === now.deepdive)
  ok('kaart 13 is de eerste stap van de gekozen verdieping', await p.innerText('.card__context') === chosen.title && await p.innerText('.card__title') === chosen.heads[0], await p.innerText('.card__title'))
  await swipeTo('.card--quiz')
  for (const q of await p.locator('.question').all()) await q.locator('.option').first().tap()
  await swipe(); ok('afgerond', await pos() === 'KLAAR')

  console.log('== Na afronden wijzigen: pas vanaf morgen')
  await p.locator('#toggle-topics').tap(); await p.waitForSelector('.topics')
  await p.locator('.topic', { hasText: 'Nederland' }).locator('input').check()
  await p.locator('.topic', { hasText: 'Natuur' }).locator('input').uncheck()
  ok('melding: vanaf morgen', (await p.innerText('.topics [role=status]')).includes('vanaf morgen'))
  ok('vandaag ongewijzigd', JSON.stringify(await picks()) === JSON.stringify(now))
  await p.reload(); await p.waitForSelector('.done')
  await p.locator('#toggle-topics').tap()
  ok('keuze blijft na herladen', await p.locator('.topic input[type=checkbox]:checked').count() === 1 && await p.locator('.topic', { hasText: 'Nederland' }).locator('input').isChecked())

  console.log('== Volgende dagen volgen de keuze')
  const seen = []
  for (let d = 1; d <= 7; d++) { await open(d); const x = await picks(); seen.push(x); if (d === 1) await finishDay() }
  ok('7 dagen alleen weetjes over Nederland, elke dag een ander', seen.every((x) => topicOf(x.fact, facts) === 'nederland') && new Set(seen.map((x) => x.fact)).size === 7, seen.map((x) => x.fact).join(', '))
  // De leerreeks over de natuur liep al: die maak je eerst af, ook nu Natuur uit staat. Dag 1 is
  // afgerond, de dagen erna niet, dus daar wacht het volgende deel.
  ok('de lopende leerreeks loopt door en wacht op een afgeronde dag', seen.every((x) => x.series?.id === 'natuur-en-geschiedenis') && seen.map((x) => x.series.part).join('') === '1222222' && seen[0].deepdive === 'aardbeving-lissabon' && seen[6].deepdive === 'jaar-zonder-zomer', seen.map((x) => `${x.deepdive}/${x.series?.part}`).join(', '))
  await p.locator('#toggle-topics').tap()
  for (const name of ['Wereldgeschiedenis', 'Wetenschap & techniek', 'Natuur & aarde', 'Taal & cultuur']) await p.locator('.topic', { hasText: name }).locator('input').check()
  ok('alles weer aan = geen filter', (await state()).topics === null)

  console.log('== Smal scherm')
  const narrow = await b.newContext({ ...devices['Pixel 7'], viewport: { width: 320, height: 640 }, locale: 'nl-NL' })
  await mockWiki(narrow); await mockTranslate(narrow)
  const np = await narrow.newPage(); await np.goto(BASE); await np.waitForSelector('.card')
  const overflow = await np.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
  ok('kop past op 320 px breed', overflow <= 0, `overloop ${overflow}px`)
  await np.screenshot({ path: out + '/72-smal.png' })

  console.log('console errors:', errors, '| mislukt:', failures())
  await b.close(); process.exit(failures() || errors.length ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
