// Leerreeksen: vijf verdiepingen die op elkaar aansluiten, met een toets na de laatste dag.
const { chromium, BASE, SHOTS: out, wait, phone, ok, failures } = require('./lib.cjs')
;(async () => {
  const load = (name) => import(require('url').pathToFileURL(require('path').join(__dirname, `../../content/${name}.js`)).href)
  const { deepdives } = await load('deepdives')
  const { facts } = await load('facts')
  const { series } = await load('series')
  const dive = (id) => deepdives.find((d) => d.id === id)
  const NL = series.find((s) => s.id === 'reformatie-tot-rampjaar'), NATUUR = series.find((s) => s.id === 'natuur-en-geschiedenis')
  const b = await chromium.launch()
  const base = Date.now()
  const key = (n) => { const d = new Date(base + n * 86400000); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` }

  // Eén telefoon met hulpjes om dagen te openen en af te ronden.
  const device = async (options) => {
    const d = await phone(b, options); const p = d.page
    d.open = async (offset) => { await p.clock.setFixedTime(new Date(base + offset * 86400000)); await p.goto(BASE); await p.waitForSelector('.card, .done') }
    d.picks = async () => Object.values((await d.state()).progress)[0].picks
    d.toDeepdive = async () => {
      await d.swipeTo('.card--history, .card--fact')
      if (await p.locator('.card--history.card--guess').count()) { await p.locator('.option').first().tap(); await wait(450); await d.swipe(); await p.locator('.skip').tap(); await wait(450); await d.swipe() }
      else if (await p.locator('.card--history').count()) await d.swipe()
      await p.locator('.skip').tap(); await wait(450); await d.swipe()
    }
    d.finish = async () => {
      if (!(await p.locator('.card--deepdive').count())) await d.toDeepdive()
      await d.swipeTo('.card--quiz')
      for (const q of await p.locator('.question').all()) await q.locator('.option').first().tap()
      await d.swipe(); await p.waitForSelector('.done')
    }
    d.seed = (patch) => p.evaluate((data) => localStorage.setItem('kennis:v1', JSON.stringify(data)), patch)
    return d
  }
  const flat = (text) => text.replace(/\s+/g, ' ').trim()

  console.log('== Dag 1: de reeks begint vanzelf')
  const d = await device(); const p = d.page
  await d.open(0)
  let pk = await d.picks()
  ok('eerste reeks, eerste deel', pk.series?.id === NL.id && pk.series.part === 0 && pk.deepdive === NL.parts[0], JSON.stringify(pk))
  await p.locator('#toggle-progress').tap(); await p.waitForSelector('.progress')
  let list = (await p.locator('.serieslist li').allInnerTexts()).map(flat)
  ok('voortgang: vijf reeksen; de eerste begint vandaag, de rest nog niet', list.length === 5 && list[0] === `${NL.title} Begint vandaag` && list.slice(1).every((t) => t.endsWith('Nog niet begonnen')) && await p.locator('.serieslist .btn').count() === 0, list.join(' | '))
  await p.locator('#toggle-progress').tap(); await p.waitForSelector('.stage .card')
  await d.toDeepdive()
  const intro = flat(await p.innerText('.card__series'))
  ok('eerste stap noemt de reeks, de dag en de inleiding', intro === `Reeks: ${NL.title} Dag 1 van 5. ${NL.intro}`, intro)
  ok('daaronder de gewone stapkaart', await p.innerText('.card__context') === dive(NL.parts[0]).title && await p.innerText('.card__title') === dive(NL.parts[0]).heads[0])
  await p.screenshot({ path: out + '/130-reeks-stap.png' })
  await d.swipe()
  ok('de volgende stappen hebben geen reeksregel', await p.locator('.card--deepdive').count() === 1 && await p.locator('.card__series').count() === 0)
  await d.finish()
  let block = flat(await p.innerText('.done__series'))
  ok('eindscherm: dag 1 gedaan, met wat er volgt', block === `Reeks: ${NL.title} Dag 1 van 5 gedaan. Volgende keer: ${dive(NL.parts[1]).title}.` && await p.locator('.done__series .btn').count() === 0, block)
  let st = await d.state()
  ok('stand bewaard: deel 2 is aan de beurt', st.series.current.id === NL.id && st.series.current.part === 1 && st.series.current.days.join() === key(0), JSON.stringify(st.series))
  await p.screenshot({ path: out + '/131-reeks-eindscherm.png', fullPage: true })
  await p.locator('#toggle-progress').tap(); await p.waitForSelector('.progress')
  ok('voortgang: 1 van 5 dagen gelezen', flat(await p.locator('.serieslist li').first().innerText()) === `${NL.title} 1 van 5 dagen gelezen`)

  console.log('== De reeks wacht op je')
  await d.open(1); pk = await d.picks()
  ok('dag 2: het tweede deel', pk.deepdive === NL.parts[1] && pk.series.part === 1)
  await d.toDeepdive()
  ok('met wat eraan voorafging', flat(await p.innerText('.card__series')) === `Reeks: ${NL.title} Dag 2 van 5. Vorige keer: ${dive(NL.parts[0]).title}.`, flat(await p.innerText('.card__series')))
  // Dag 2 niet afgerond, dag 3 overgeslagen, dag 4 geopend: nog steeds het tweede deel.
  await d.open(3); pk = await d.picks()
  ok('niet afgerond en een dag overgeslagen: het tweede deel staat er nog', pk.deepdive === NL.parts[1] && pk.series.part === 1, pk.deepdive)
  await d.finish()
  await d.open(4); ok('daarna het derde deel', (await d.picks()).deepdive === NL.parts[2]); await d.finish()

  console.log('== Onderwerpen wijzigen tijdens een reeks')
  await d.open(5)
  await p.locator('#toggle-topics').tap(); await p.waitForSelector('.topics')
  for (const name of ['Nederland', 'Wereldgeschiedenis', 'Wetenschap & techniek', 'Taal & cultuur']) await p.locator('.topic', { hasText: name }).locator('input').uncheck()
  pk = await d.picks()
  ok('alleen Natuur gekozen: het weetje volgt, de lopende reeks loopt door', facts.find((f) => f.id === pk.fact).topic === 'natuur' && pk.deepdive === NL.parts[3] && pk.series.part === 3, `${pk.fact} | ${pk.deepdive}`)
  for (const name of ['Nederland', 'Wereldgeschiedenis', 'Wetenschap & techniek', 'Taal & cultuur']) await p.locator('.topic', { hasText: name }).locator('input').check()
  ok('alles weer aan: nog steeds het vierde deel', (await d.picks()).deepdive === NL.parts[3] && (await d.state()).topics === null)
  await p.locator('text=Terug naar de editie').tap(); await p.waitForSelector('.stage .card')
  await d.finish()

  console.log('== Dag vijf: reeks afgerond en reekstoets')
  await d.open(6); ok('vijfde deel', (await d.picks()).deepdive === NL.parts[4]); await d.finish()
  st = await d.state()
  const days = [0, 3, 4, 5, 6].map(key)
  ok('reeks afgerond en vastgelegd, met de dagen waarop je las', st.series.current === null && st.series.gap === 0 && st.series.done[NL.id].day === key(6) && st.series.done[NL.id].days.join() === days.join() && st.series.done[NL.id].score === null, JSON.stringify(st.series))
  block = flat(await p.innerText('.done__series'))
  ok('eindscherm biedt de reekstoets aan', block.includes('Reeks afgerond: alle 5 dagen gelezen') && await p.locator('.done__series .btn').innerText() === 'Reekstoets: 5 vragen', block)
  await p.screenshot({ path: out + '/132-reeks-afgerond.png', fullPage: true })
  await p.locator('.done__series .btn').tap(); await p.waitForSelector('.week')
  const labels = (await p.locator('.question__tag').allInnerTexts()).map((t) => t.toUpperCase())
  ok('vijf vragen, één per dag, met de titel van dat deel', labels.length === 5 && labels.every((l, i) => l === `DAG ${i + 1} · ${dive(NL.parts[i]).title}`.toUpperCase()) && (await p.innerText('.week .card__kicker')).toUpperCase() === 'REEKSTOETS' && await p.innerText('.week .card__title') === NL.title, labels.join(' | '))
  ok('de vragen zijn de eerste vraag van elke verdieping', (await p.locator('.question legend').allInnerTexts()).every((t, i) => t.includes(dive(NL.parts[i]).question.q)))
  ok('afronden kan pas na alle antwoorden', await p.locator('.week__actions .btn:not(.btn--ghost)').isDisabled())
  await p.screenshot({ path: out + '/133-reekstoets.png' })
  const right = (i) => dive(NL.parts[i]).question.options[dive(NL.parts[i]).question.answer]
  const wrong = (i) => dive(NL.parts[i]).question.options.find((o) => o !== right(i))
  const answer = async (i, text) => { await p.locator('.question').nth(i).locator('.option', { hasText: text }).first().tap() }
  await answer(0, right(0)); await answer(1, wrong(1))
  await p.locator('text=Later verder').tap(); await p.waitForSelector('.done')
  ok('halverwege: knop "Reekstoets afmaken"', await p.locator('.done__series .btn').innerText() === 'Reekstoets afmaken')
  // De volgende dag verder: de antwoorden en hun volgorde zijn bewaard.
  const order = async () => JSON.stringify(await p.locator('.week .option').allInnerTexts())
  await p.locator('.done__series .btn').tap(); await p.waitForSelector('.week'); const shown = await order()
  await d.open(7)
  await p.locator('#toggle-progress').tap(); await p.waitForSelector('.progress')
  list = (await p.locator('.serieslist li').allInnerTexts()).map(flat)
  ok('voortgang een dag later: afgerond, toets nog af te maken', list[0].startsWith(`${NL.title} Afgerond op `) && list[0].endsWith('Reekstoets afmaken'), list[0])
  await p.locator('.serieslist .btn').tap(); await p.waitForSelector('.week')
  ok('een dag later dezelfde volgorde en dezelfde twee antwoorden', (await order()).replace(/ [✓✗]/g, '') === shown.replace(/ [✓✗]/g, '') && await p.locator('.week .option:disabled').count() === 6)
  const logBefore = (await d.state()).log
  await answer(2, right(2)); await answer(3, right(3)); await answer(4, wrong(4))
  await p.locator('text=Reekstoets afronden').tap(); await wait(200)
  ok('score getoond: 3 van 5', flat(await p.innerText('.week__score')).includes('3 van 5'), flat(await p.innerText('.week__score')))
  st = await d.state()
  const touched = st.log.filter((item) => item.lastReview === key(7) && days.includes(item.day) && item.type === 'deepdive').length
  const stillThere = logBefore.filter((item) => days.includes(item.day) && item.type === 'deepdive').length
  ok('score vastgelegd; de antwoorden tellen mee voor de herhaling', st.series.done[NL.id].score.join() === '3,5' && stillThere > 0 && touched + (logBefore.length - st.log.length) === stillThere, `${stillThere} vragen in de herhaling, ${touched} bijgewerkt, ${logBefore.length - st.log.length} onthouden`)
  await p.locator('.week__actions .btn--ghost').tap(); await p.waitForSelector('.progress')
  list = (await p.locator('.serieslist li').allInnerTexts()).map(flat)
  ok('terug op het voortgangsscherm, met de toetsscore', list[0].includes('toets 3 van 5') && list[0].endsWith('Reekstoets bekijken'), list[0])
  await p.screenshot({ path: out + '/134-reeksen-voortgang.png', fullPage: true })
  await p.locator('.serieslist .btn').tap(); await p.waitForSelector('.week')
  ok('bekijken: alles staat vast, geen knop om af te ronden', await p.locator('.week .option:disabled').count() === 15 && await p.locator('text=Reekstoets afronden').count() === 0)

  console.log('== Twee losse dagen, dan de volgende reeks')
  const inSeries = new Set(series.flatMap((s) => s.parts))
  await d.open(7); const first = await d.picks()
  ok('dag na de reeks: een verdieping die bij geen enkele reeks hoort', first.series === null && !inSeries.has(first.deepdive), first.deepdive)
  // Niet afgerond: de dag telt niet als losse dag, en de verdieping blijft dezelfde.
  await d.open(8); pk = await d.picks()
  ok('losse dag niet afgerond: dezelfde verdieping staat er de volgende dag nog', pk.series === null && pk.deepdive === first.deepdive && (await d.state()).series.gap === 0, pk.deepdive)
  ok('eindscherm zonder reeksblok', (await d.finish(), await p.locator('.done__series').count()) === 0)
  await d.open(9); const second = await d.picks()
  ok('tweede losse dag: een andere verdieping, ook buiten de reeksen', second.series === null && second.deepdive !== first.deepdive && !inSeries.has(second.deepdive), `${first.deepdive} -> ${second.deepdive}`)
  await d.finish()
  await d.open(10); pk = await d.picks()
  ok('daarna start de tweede reeks', pk.series?.id === NATUUR.id && pk.series.part === 0 && pk.deepdive === NATUUR.parts[0] && (await d.state()).series.gap === 2, JSON.stringify(pk))
  ok('geen fouten in de console', d.errors.length === 0, d.errors.join(' | '))
  await d.ctx.close()

  console.log('== Eén onderwerp: te weinig losse verdiepingen voor twee dagen pauze')
  const doneNL = { [NL.id]: { day: key(-1), days: [], answers: [], score: null } }
  const f = await device(); await f.open(0)
  await f.seed({ topics: ['natuur'], series: { current: null, gap: 0, done: doneNL }, progress: {}, saved: [], log: [] })
  await f.open(0); pk = await f.picks()
  ok('alleen Natuur: de ene losse verdieping (de dodo), niets uit de komende reeks', pk.series === null && pk.deepdive === 'dodo', pk.deepdive)
  await f.finish(); await f.open(1); pk = await f.picks()
  ok('na één losse dag start de reeks over de natuur al', pk.series?.id === NATUUR.id && pk.deepdive === NATUUR.parts[0], JSON.stringify(pk))
  await f.seed({ topics: ['wetenschap'], series: { current: null, gap: 0, done: doneNL }, progress: {}, saved: [], log: [] })
  await f.open(0); pk = await f.picks()
  const science = series.find((s) => s.topic === 'wetenschap')
  ok('alleen Wetenschap (geen losse verdiepingen): de reeks start meteen', pk.series?.id === science.id && pk.deepdive === science.parts[0], JSON.stringify(pk))
  ok('geen fouten in de console', f.errors.length === 0, f.errors.join(' | '))
  await f.ctx.close()

  console.log('== Alle reeksen gedaan')
  const allDone = (ago) => Object.fromEntries(series.map((s, i) => [s.id, { day: key(-ago - i), days: [], answers: [], score: null }]))
  const e = await device(); await e.open(0)
  await e.seed({ series: { current: null, gap: 2, done: allDone(10) }, progress: {}, saved: [], log: [] })
  await e.open(0); pk = await e.picks()
  ok('kort geleden afgerond en de pauze voorbij: een verdieping uit de hele lijst', pk.series === null && !!dive(pk.deepdive), pk.deepdive)
  await e.seed({ series: { current: null, gap: 2, done: allDone(60) }, progress: {}, saved: [], log: [] })
  await e.open(0); pk = await e.picks()
  ok('zestig dagen later: de reeks die het langst geleden is afgerond komt terug', pk.series?.id === series[series.length - 1].id && pk.series.part === 0, JSON.stringify(pk.series))
  await e.page.locator('#toggle-progress').tap(); await e.page.waitForSelector('.progress')
  list = (await e.page.locator('.serieslist li').allInnerTexts()).map(flat)
  ok('zonder herleesbare dagen kan de toets toch (de vragen komen uit de inhoud)', list[0].endsWith('Reekstoets: 5 vragen') && list[4].endsWith('Begint vandaag'), `${list[0]} | ${list[4]}`)
  await e.page.locator('.serieslist .btn').first().tap(); await e.page.waitForSelector('.week')
  for (const q of await e.page.locator('.question').all()) await q.locator('.option').first().tap()
  await e.page.locator('text=Reekstoets afronden').tap(); await wait(200)
  ok('toets afronden werkt ook zonder vragen in de herhaling', (await e.state()).series.done[series[0].id].score?.[1] === 5)

  console.log('== Beschadigde opslag')
  await e.seed({ series: { current: { id: '../x', part: 'a' }, gap: -5, done: { ['__proto__']: { day: 'x' }, 'Reeks Met Spaties': { day: key(-1) }, [NL.id]: { day: 'geen-datum' }, [NATUUR.id]: { day: key(-3), days: 'x', answers: 7, score: [9] } } }, progress: {}, saved: [], log: [] })
  await e.open(0); st = await e.state()
  ok('ongeldige stand wordt opgeschoond; de app start gewoon', st.series.current === null && st.series.gap === 0 && Object.keys(st.series.done).join() === NATUUR.id && Array.isArray(st.series.done[NATUUR.id].answers) && st.series.done[NATUUR.id].score === null && await e.page.locator('.card').count() === 1, JSON.stringify(st.series))
  await e.seed({ series: { current: { id: 'bestaat-niet', part: 2, days: [] }, gap: 0, done: {} }, progress: {}, saved: [], log: [] })
  await e.open(0); pk = await e.picks()
  ok('een reeks die niet meer bestaat: verder met een losse verdieping', pk.series === null && !!dive(pk.deepdive), JSON.stringify(pk))
  await e.seed({ series: { current: { id: NL.id, part: 9, days: [] }, gap: 2, done: {} }, progress: {}, saved: [], log: [] })
  await e.open(0); pk = await e.picks()
  ok('een deel dat niet bestaat: de reeks begint opnieuw bij het begin', pk.series?.id === NL.id && pk.series.part === 0, JSON.stringify(pk))
  // De vastgelegde keuze past niet meer bij de inhoud: de kaart toont dan geen reeksregel.
  await e.page.evaluate((id) => { const s = JSON.parse(localStorage.getItem('kennis:v1')); const k = Object.keys(s.progress)[0]; s.progress[k].picks.deepdive = id; localStorage.setItem('kennis:v1', JSON.stringify(s)) }, 'dodo')
  await e.open(0); await e.toDeepdive()
  ok('keuze en reeks kloppen niet met elkaar: gewone stapkaart, geen reeksregel', await e.page.innerText('.card__context') === dive('dodo').title && await e.page.locator('.card__series').count() === 0)
  await e.finish()
  ok('en de dag telt dan als losse dag', (await e.state()).series.current?.part === 9 && await e.page.locator('.done__series').count() === 0, JSON.stringify((await e.state()).series))
  ok('geen fouten in de console', e.errors.length === 0, e.errors.join(' | '))

  console.log('mislukt:', failures()); await b.close(); process.exit(failures() ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
