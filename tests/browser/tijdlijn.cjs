const { chromium, BASE, wait, phone, ok, failures } = require('./lib.cjs')
const { SHOTS: out } = require('./lib.cjs')
;(async () => {
  const b = await chromium.launch()
  const { page: p, errors, swipe, swipeTo, pos, state } = await phone(b)
  const base = Date.now()
  const open = async (offset) => { await p.clock.setFixedTime(new Date(base + offset * 86400000)); await p.goto(BASE); await p.waitForSelector('.card, .done') }
  const toTimeline = async () => { await swipeTo('.card--history'); await p.locator('.option', { hasText: '1760' }).tap(); await wait(450); await swipe() }
  const timeline = () => p.evaluate(() => JSON.parse(localStorage.getItem('kennis:edition:v9')).history.timeline)
  const badges = () => p.locator('.timeline__badge').allInnerTexts()
  const tapItem = (i) => p.locator('.timeline__item').nth(i).tap()

  console.log('== Dag 1: goed')
  await open(0)
  ok('12 kaarten', await p.locator('.steps li').count() === 12)
  await toTimeline()
  ok('kaart 6 is de tijdlijn', (await pos()) === '9 / 12' && await p.locator('.card--timeline.card--guess').count() === 1)
  const t = await timeline()
  console.log('   items:', t.items.map((i) => `${i.label}: ${i.text.slice(0, 60)}`).join('\n          '))
  ok('3 gebeurtenissen, verschillende jaren, niet al op volgorde', t.items.length === 3 && new Set(t.items.map((i) => i.year)).size === 3 && !t.items.every((x, i) => i === 0 || t.items[i - 1].year < x.year))
  ok('jaartallen niet zichtbaar op de voorkant', !t.items.some((i) => false) && !/\b(1908|1943|2000)\b/.test((await p.locator('.timeline__badge').allInnerTexts()).join('')) && await p.locator('.timeline__year').count() === 0)
  ok('Controleer uitgeschakeld', await p.locator('.timeline__actions .btn').isDisabled())
  await p.screenshot({ path: out + '/60-tijdlijn-leeg.png' })
  await swipe(); ok('vegen geblokkeerd', (await pos()) === '9 / 12', await p.innerText('.pager__hint'))
  await tapItem(0); await tapItem(1); await tapItem(2)
  ok('nummers 1-2-3 in tikvolgorde', (await badges()).join('') === '123')
  await tapItem(1)
  ok('opnieuw tikken haalt weg en hernummert', (await badges()).join(',') === '1,,2', (await badges()).join(','))
  await tapItem(0); await tapItem(2)
  const right = t.items.map((_, i) => i).sort((a, c) => t.items[a].year - t.items[c].year)
  for (const i of right) await tapItem(i)
  await p.screenshot({ path: out + '/61-tijdlijn-gekozen.png' })
  await p.locator('.timeline__actions .btn').tap(); await wait(100)
  ok('omgedraaid met animatie', await p.locator('.card.flip-in').count() === 1); await wait(450)
  ok('uitslag goed', (await p.innerText('.result')).includes('Goed') && await p.locator('.timeline__result li.is-correct').count() === 3)
  ok('jaartallen oplopend getoond', JSON.stringify(await p.locator('.timeline__year').allInnerTexts()) === JSON.stringify([...t.items].sort((a, c) => a.year - c.year).map((i) => i.label)), (await p.locator('.timeline__year').allInnerTexts()).join(' < '))
  ok('bron en vertaalregel', (await p.getAttribute('.card__foot a', 'href')) === 'https://en.wikipedia.org/wiki/November_15' || (await p.getAttribute('.card__foot a', 'href')).startsWith('https://en.wikipedia.org/wiki/'), await p.innerText('.card__foot'))
  await p.screenshot({ path: out + '/62-tijdlijn-goed.png' })
  await p.reload(); await p.waitForSelector('.card')
  ok('uitslag blijft na herladen', (await pos()) === '9 / 12' && await p.locator('.result.is-correct').count() === 1)
  await swipe(); ok('daarna verder', (await pos()) === '10 / 12')
  await p.locator('.skip').tap(); await wait(450); await swipe(); await swipe()
  for (const q of await p.locator('.question').all()) await q.locator('.option').first().tap()
  await swipe()
  console.log('   klaar:', (await p.innerText('.stats')).replace(/\n+/g, ' | '))
  ok('Geraden telt 3 kaarten, 2 goed', (await p.innerText('.stats')).includes('2 van 3'))
  ok('log bevat 4 vragen (tijdlijn niet)', (await state()).log.length === 4)

  console.log('== Dag 2: fout')
  await open(1); await toTimeline()
  const t2 = await timeline()
  const r2 = t2.items.map((_, i) => i).sort((a, c) => t2.items[a].year - t2.items[c].year)
  for (const i of [r2[1], r2[0], r2[2]]) await tapItem(i)
  await p.locator('.timeline__actions .btn').tap(); await wait(500)
  ok('uitslag fout met jouw plek', (await p.innerText('.result')).includes('Niet helemaal') && await p.locator('.timeline__result li.is-wrong').count() === 2 && (await p.locator('.timeline__note').allInnerTexts()).join(' ').includes('plek 2'), (await p.locator('.timeline__note').allInnerTexts()).join(' / '))
  await p.screenshot({ path: out + '/63-tijdlijn-fout.png' })

  console.log('== Dag 3: geen idee')
  await open(2); await toTimeline()
  await p.locator('.skip').tap(); await wait(500)
  ok('neutrale uitslag met juiste volgorde', await p.locator('.result.is-neutral').count() === 1 && await p.locator('.timeline__result li').count() === 3 && await p.locator('.timeline__note').count() === 0)

  console.log('== Wikipedia onbereikbaar')
  const { ctx: c2, page: p2 } = await phone(b, { wiki: false })
  await c2.route(/wikimedia/, (r) => r.abort())
  await p2.goto(BASE); await p2.waitForSelector('.card')
  ok('geen tijdlijnkaart, editie werkt', await p2.locator('.steps li').count() === 11, (await p2.locator('.notice').allInnerTexts()).join(' / '))

  console.log('== Vertalen mislukt')
  const { ctx: c3, page: p3, swipe: s3, swipeTo: st3 } = await phone(b, { translate: false })
  await c3.route(/mymemory/, (r) => r.abort())
  await p3.goto(BASE); await p3.waitForSelector('.card')
  ok('melding', (await p3.locator('.notice').allInnerTexts()).join(' ').includes('Vertalen lukte niet'))
  await st3('.card--history'); await p3.locator('.option', { hasText: '1760' }).tap(); await wait(450); await s3()
  ok('tijdlijn in het Engels, zonder vertaalregel', await p3.getAttribute('.options', 'lang') === 'en' && !(await p3.innerText('.card')).includes('[nl]'), (await p3.locator('.timeline__item').first().innerText()).slice(0, 60))

  console.log('console errors:', errors, '| mislukt:', failures())
  await b.close(); process.exit(failures() || errors.length ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
